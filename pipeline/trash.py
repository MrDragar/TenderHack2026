import re

# Объявления, торг и условия сделки к товару не относятся: просим человека убрать.
NOISE = {
    "продам",
    "продаю",
    "продается",
    "торг",
    "торгуюсь",
    "срочно",
    "недорого",
    "дешево",
    "доставка",
    "самовывоз",
    "опт",
    "оптом",
    "розница",
    "наличными",
    "договорная",
    "гарантия",
    "звоните",
    "пишите",
    "обращайтесь",
    "авито",
    "нерабочий",
}
CONTACT = re.compile(r"https?://|www\.|@|\+\d|\.(?:ru|com|net|org)\b", re.IGNORECASE)
CYRILLIC = re.compile(r"[а-яё]", re.IGNORECASE)


def trash(text: str) -> bool:
    """Мусор, если это объявление или контакт, либо слово не по-русски: остаток из цифр,
    латиницы или символов товарной характеристикой быть не может. Иначе считаем, что это
    настоящая характеристика, которую пайплайн не разобрал, и отдаём модератору."""
    if text.casefold().replace("ё", "е") in NOISE:
        return True
    return bool(CONTACT.search(text)) or not CYRILLIC.search(text)
